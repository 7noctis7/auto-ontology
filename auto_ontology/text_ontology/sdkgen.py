def _safe(name: str) -> str:
    """A Python identifier for *name*: never a keyword, never starting with a digit."""
    cleaned = re.sub(r"[^0-9A-Za-z_]", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = "T_" + cleaned
    if keyword.iskeyword(cleaned) or keyword.issoftkeyword(cleaned):
        cleaned += "_"
    return cleaned


def _unique(name: str, used: set[str]) -> str:
    """*name*, numbered when another type already took it (``A-B`` and ``A_B``)."""
    candidate, number = name, 2
    while candidate in used:
        candidate, number = f"{name}_{number}", number + 1
    used.add(candidate)
    return candidate
